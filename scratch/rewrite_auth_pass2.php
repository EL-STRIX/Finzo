<?php

$files = [
    'resources/views/auth/admin-login.html',
    'resources/views/auth/forgot-password.html',
    'resources/views/auth/login.html',
    'resources/views/auth/register.html',
    'resources/views/auth/reset-password.html',
    'resources/views/auth/staff-login.html'
];

foreach ($files as $file) {
    if (!file_exists($file)) continue;

    $content = file_get_contents($file);

    // 1. Remove all animation classes
    $content = str_replace('fade-in-up', '', $content);
    $content = preg_replace('/\s*style="animation-delay:[^"]*"/', '', $content);
    $content = preg_replace('/\s*style="transition-delay:[^"]*"/', '', $content);

    // 2. Fix duplicate classes generated by previous replace
    $content = str_replace('text-slate-900 tracking-tight text-slate-900', 'text-slate-900 tracking-tight', $content);
    $content = str_replace('text-slate-900 text-white', 'text-white', $content);
    $content = str_replace('space-y-6 space-y-4 sm:space-y-5', 'space-y-6', $content);
    $content = str_replace('space-y-6  w-full', 'space-y-6 w-full', $content);
    $content = str_replace('border border-slate-200 p-1 bg-slate-50', 'bg-slate-50', $content); // Role switcher double class fix
    
    // 3. Remove dark mode toggles or unused stuff if they exist
    $content = str_replace('dark:bg-white', '', $content);
    $content = str_replace('dark:border-slate-200', '', $content);

    // 4. Ensure proper enterprise look for register.html
    $content = str_replace('bg-background', 'bg-slate-50', $content);
    $content = str_replace('text-accent', 'text-blue-600', $content);
    $content = str_replace('bg-accent', 'bg-blue-600', $content);
    
    // Clean up empty lines and multi-spaces from replacement
    $content = preg_replace('/ {2,}/', ' ', $content);
    
    // Write back
    file_put_contents($file, $content);
}

echo "Auth UI Pass 2 complete.";
